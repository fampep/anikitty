/** Sign-in required against the locked dedicated Go server. Always dark UI. */
@Composable
fun AppRoot(
    api: DedicatedApiClient,
    session: SessionStore,
    savedPassphrase: SavedPassphraseStore,
    serverConfig: ServerConfig,
    aniList: AniListClient,
    historyDao: WatchHistoryDao,
    streamServers: ServerCatalog,
) {
    var signedIn by remember { mutableStateOf(session.isSignedIn) }
    val scope = rememberCoroutineScope()

    if (!signedIn) {
        LoginScreen(
            api = api,
            session = session,
            savedPassphrase = savedPassphrase,
            dedicatedUrl = serverConfig.baseUrl,
            onSignedIn = { signedIn = true },
        )
    } else {
        LocalFirstApp(
            aniList = aniList,
            historyDao = historyDao,
            streamServers = streamServers,
            username = session.username ?: "user",
            serverBaseUrl = serverConfig.baseUrl,
            onSignOut = {
                val token = session.token
                session.clear()
                signedIn = false
                if (!token.isNullOrBlank()) {
                    scope.launch { runCatching { api.logout(token) } }
                }
            },
        )
    }
}

@Composable
private fun LoginScreen(
    api: DedicatedApiClient,
    session: SessionStore,
    savedPassphrase: SavedPassphraseStore,
    dedicatedUrl: String,
    onSignedIn: () -> Unit,
) {
    var username by remember { mutableStateOf(savedPassphrase.username.orEmpty()) }
    var passphrase by remember { mutableStateOf("") }
    var showPassphrase by remember { mutableStateOf(false) }
    var saveOnDevice by remember { mutableStateOf(true) }
    var generated by remember { mutableStateOf<String?>(null) }
    var status by remember {
        mutableStateOf("Sign in with your username + passphrase. Same passphrase works on the host.")
    }
    var busy by remember { mutableStateOf(false) }
    val scope = rememberCoroutineScope()
    val hasSaved = savedPassphrase.hasSaved

    fun run(label: String, block: suspend () -> String) {
        scope.launch {
            busy = true
            status = label
            status = runCatching { block() }.getOrElse { e -> "Error: ${e.message}" }
            busy = false
        }
    }

    fun persistIfNeeded(user: String, pass: String) {
        if (saveOnDevice) savedPassphrase.save(user, pass) else Unit
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(24.dp),
        verticalArrangement = Arrangement.Center,
        horizontalAlignment = Alignment.CenterHorizontally,
    ) {
        Text("AniKitty", style = MaterialTheme.typography.headlineMedium)
        Text(
            "Dark APK · dedicated auth host (URL locked)",
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        Spacer(modifier = Modifier.height(8.dp))
        Text(
            dedicatedUrl,
            style = MaterialTheme.typography.labelMedium,
            fontFamily = FontFamily.Monospace,
            color = MaterialTheme.colorScheme.primary,
        )
        Spacer(modifier = Modifier.height(20.dp))

        OutlinedTextField(
            value = username,
            onValueChange = { username = it.filter { ch -> ch.isLetterOrDigit() || ch == '_' } },
            modifier = Modifier.fillMaxWidth(),
            singleLine = true,
            label = { Text("Username (3–32, letters/numbers/_)") },
            enabled = !busy,
        )
        Spacer(modifier = Modifier.height(8.dp))
        OutlinedTextField(
            value = passphrase,
            onValueChange = { passphrase = it },
            modifier = Modifier.fillMaxWidth(),
            singleLine = true,
            label = { Text("Passphrase") },
            visualTransformation = if (showPassphrase) {
                VisualTransformation.None
            } else {
                PasswordVisualTransformation()
            },
            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
            enabled = !busy,
            supportingText = {
                Text("Host login secret — generate one or type the passphrase from signup.")
            },
        )
        TextButton(
            onClick = { showPassphrase = !showPassphrase },
            enabled = !busy,
        ) {
            Text(if (showPassphrase) "Hide passphrase" else "Show passphrase")
        }

        Row(
            verticalAlignment = Alignment.CenterVertically,
            modifier = Modifier.fillMaxWidth(),
        ) {
            Checkbox(
                checked = saveOnDevice,
                onCheckedChange = { saveOnDevice = it },
                enabled = !busy,
            )
            Text(
                "Save passphrase on this phone/tablet for quick sign-in",
                style = MaterialTheme.typography.bodySmall,
            )
        }

        Spacer(modifier = Modifier.height(12.dp))
        Button(
            onClick = {
                run("Signing in...") {
                    val user = username.trim()
                    val pass = passphrase.trim()
                    require(user.length in 3..32) { "username must be 3–32 chars" }
                    require(pass.length >= 10) { "passphrase must be at least 10 characters" }
                    val res = api.login(user, pass)
                    session.token = res.token
                    session.username = res.username
                    persistIfNeeded(user, pass)
                    onSignedIn()
                    "Welcome ${res.username}"
                }
            },
            enabled = !busy && username.length >= 3 && passphrase.length >= 10,
            modifier = Modifier.fillMaxWidth(),
        ) { Text("Sign in with passphrase") }

        if (hasSaved) {
            Spacer(modifier = Modifier.height(8.dp))
            OutlinedButton(
                onClick = {
                    run("Signing in with saved passphrase...") {
                        val user = savedPassphrase.username
                            ?: error("no saved username")
                        val pass = savedPassphrase.passphrase
                            ?: error("no saved passphrase")
                        val res = api.login(user, pass)
                        session.token = res.token
                        session.username = res.username
                        username = user
                        passphrase = pass
                        onSignedIn()
                        "Welcome ${res.username} (saved on device)"
                    }
                },
                enabled = !busy,
                modifier = Modifier.fillMaxWidth(),
            ) { Text("Sign in with saved passphrase") }
            TextButton(
                onClick = {
                    savedPassphrase.clear()
                    status = "Cleared passphrase saved on this device."
                },
                enabled = !busy,
            ) { Text("Forget saved passphrase") }
        }

        Spacer(modifier = Modifier.height(16.dp))
        Text("New account", style = MaterialTheme.typography.titleSmall)
        OutlinedButton(
            onClick = {
                val pass = Passphrase.generate()
                generated = pass
                passphrase = pass
                showPassphrase = true
                status = "New random passphrase generated — create the account next (write it down)."
            },
            enabled = !busy,
            modifier = Modifier.fillMaxWidth(),
        ) { Text("Generate random passphrase") }

        if (generated != null) {
            Spacer(modifier = Modifier.height(8.dp))
            Text(
                generated!!,
                style = MaterialTheme.typography.titleSmall,
                fontFamily = FontFamily.Monospace,
                color = MaterialTheme.colorScheme.primary,
            )
            Text(
                "Save this passphrase — it is the only way to sign in on the host.",
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }

        Spacer(modifier = Modifier.height(8.dp))
        Button(
            onClick = {
                run("Creating account...") {
                    val user = username.trim()
                    val pass = passphrase.trim().ifBlank {
                        Passphrase.generate().also {
                            generated = it
                            passphrase = it
                            showPassphrase = true
                        }
                    }
                    require(user.length in 3..32) { "username must be 3–32 chars" }
                    require(pass.length >= 10) { "passphrase too short" }
                    val res = api.signup(user, pass)
                    session.token = res.token
                    session.username = res.username
                    persistIfNeeded(user, pass)
                    onSignedIn()
                    "Account created. Passphrase is your host login secret."
                }
            },
            enabled = !busy && username.length >= 3,
            modifier = Modifier.fillMaxWidth(),
        ) { Text("Create account") }

        Spacer(modifier = Modifier.height(16.dp))
        Text(status, style = MaterialTheme.typography.bodySmall)
    }
}
