/** Sign-in against the locked dedicated host. UI inspired by anilab.so (dark + brand red). */
@Composable
fun AppRoot(
    api: DedicatedApiClient,
    session: SessionStore,
    savedPassphrase: SavedPassphraseStore,
    aniList: AniListClient,
    historyDao: WatchHistoryDao,
    streamServers: ServerCatalog,
) {
    var signedIn by remember { mutableStateOf(session.isSignedIn) }
    val scope = rememberCoroutineScope()

    if (!signedIn) {
        LoginScreen(
            api = api,
            session = session,
            savedPassphrase = savedPassphrase,
            onSignedIn = { signedIn = true },
        )
    } else {
        LocalFirstApp(
            aniList = aniList,
            historyDao = historyDao,
            streamServers = streamServers,
            username = session.username ?: "user",
            onSignOut = {
                val token = session.token
                session.clear()
                signedIn = false
                if (!token.isNullOrBlank()) {
                    scope.launch { runCatching { api.logout(token) } }
                }
            },
        )
    }
}

@Composable
private fun LoginScreen(
    api: DedicatedApiClient,
    session: SessionStore,
    savedPassphrase: SavedPassphraseStore,
    onSignedIn: () -> Unit,
) {
    var username by remember { mutableStateOf(savedPassphrase.username.orEmpty()) }
    var passphrase by remember { mutableStateOf("") }
    var showPassphrase by remember { mutableStateOf(false) }
    var saveOnDevice by remember { mutableStateOf(true) }
    var generated by remember { mutableStateOf<String?>(null) }
    var status by remember {
        mutableStateOf("Sign in to sync your account. Passphrase works on this device and the host.")
    }
    var busy by remember { mutableStateOf(false) }
    val scope = rememberCoroutineScope()
    val hasSaved = savedPassphrase.hasSaved

    val fieldColors = OutlinedTextFieldDefaults.colors(
        focusedBorderColor = MaterialTheme.colorScheme.primary,
        unfocusedBorderColor = MaterialTheme.colorScheme.outline,
        focusedLabelColor = MaterialTheme.colorScheme.primary,
        cursorColor = MaterialTheme.colorScheme.primary,
        focusedTextColor = MaterialTheme.colorScheme.onSurface,
        unfocusedTextColor = MaterialTheme.colorScheme.onSurface,
    )

    fun run(label: String, block: suspend () -> String) {
        scope.launch {
            busy = true
            status = label
            status = runCatching { block() }.getOrElse { e -> "Error: ${e.message}" }
            busy = false
        }
    }

    fun persistIfNeeded(user: String, pass: String) {
        if (saveOnDevice) savedPassphrase.save(user, pass)
    }

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(MaterialTheme.colorScheme.background)
            .background(
                Brush.verticalGradient(
                    listOf(
                        Color(0xFF2A0508),
                        MaterialTheme.colorScheme.background,
                        MaterialTheme.colorScheme.background,
                    ),
                ),
            ),
    ) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 28.dp, vertical = 40.dp),
            verticalArrangement = Arrangement.Center,
            horizontalAlignment = Alignment.CenterHorizontally,
        ) {
            Text(
                "AniKitty",
                style = MaterialTheme.typography.displaySmall,
                fontWeight = FontWeight.Black,
                color = Color.White,
            )
            Spacer(modifier = Modifier.height(8.dp))
            Text(
                "Watch anime free · no ads",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                textAlign = TextAlign.Center,
            )
            Spacer(modifier = Modifier.height(6.dp))
            Text(
                "Secure account login",
                style = MaterialTheme.typography.labelLarge,
                color = MaterialTheme.colorScheme.primary,
                fontWeight = FontWeight.SemiBold,
            )

            Spacer(modifier = Modifier.height(28.dp))

            OutlinedTextField(
                value = username,
                onValueChange = { username = it.filter { ch -> ch.isLetterOrDigit() || ch == '_' } },
                modifier = Modifier.fillMaxWidth(),
                singleLine = true,
                label = { Text("Username") },
                enabled = !busy,
                shape = RoundedCornerShape(8.dp),
                colors = fieldColors,
            )
            Spacer(modifier = Modifier.height(12.dp))
            OutlinedTextField(
                value = passphrase,
                onValueChange = { passphrase = it },
                modifier = Modifier.fillMaxWidth(),
                singleLine = true,
                label = { Text("Passphrase") },
                visualTransformation = if (showPassphrase) {
                    VisualTransformation.None
                } else {
                    PasswordVisualTransformation()
                },
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                enabled = !busy,
                shape = RoundedCornerShape(8.dp),
                colors = fieldColors,
            )
            TextButton(onClick = { showPassphrase = !showPassphrase }, enabled = !busy) {
                Text(
                    if (showPassphrase) "Hide passphrase" else "Show passphrase",
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }

            Row(
                verticalAlignment = Alignment.CenterVertically,
                modifier = Modifier.fillMaxWidth(),
            ) {
                Checkbox(
                    checked = saveOnDevice,
                    onCheckedChange = { saveOnDevice = it },
                    enabled = !busy,
                    colors = CheckboxDefaults.colors(
                        checkedColor = MaterialTheme.colorScheme.primary,
                    ),
                )
                Text(
                    "Save passphrase on this device",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }

            Spacer(modifier = Modifier.height(16.dp))
            Button(
                onClick = {
                    run("Signing in...") {
                        val user = username.trim()
                        val pass = passphrase.trim()
                        require(user.length in 3..32) { "username must be 3–32 chars" }
                        require(pass.length >= 10) { "passphrase must be at least 10 characters" }
                        val res = api.login(user, pass)
                        session.token = res.token
                        session.username = res.username
                        persistIfNeeded(user, pass)
                        onSignedIn()
                        "Welcome ${res.username}"
                    }
                },
                enabled = !busy && username.length >= 3 && passphrase.length >= 10,
                modifier = Modifier
                    .fillMaxWidth()
                    .height(48.dp),
                shape = RoundedCornerShape(6.dp),
                colors = ButtonDefaults.buttonColors(
                    containerColor = MaterialTheme.colorScheme.primary,
                    contentColor = Color.White,
                ),
            ) {
                Text("Sign in", fontWeight = FontWeight.Bold)
            }

            if (hasSaved) {
                Spacer(modifier = Modifier.height(10.dp))
                OutlinedButton(
                    onClick = {
                        run("Signing in with saved passphrase...") {
                            val user = savedPassphrase.username ?: error("no saved username")
                            val pass = savedPassphrase.passphrase ?: error("no saved passphrase")
                            val res = api.login(user, pass)
                            session.token = res.token
                            session.username = res.username
                            username = user
                            passphrase = pass
                            onSignedIn()
                            "Welcome ${res.username}"
                        }
                    },
                    enabled = !busy,
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(6.dp),
                ) { Text("Continue with saved passphrase") }
                TextButton(
                    onClick = {
                        savedPassphrase.clear()
                        status = "Cleared saved passphrase on this device."
                    },
                    enabled = !busy,
                ) { Text("Forget saved passphrase", color = MaterialTheme.colorScheme.onSurfaceVariant) }
            }

            Spacer(modifier = Modifier.height(28.dp))
            Text(
                "New here?",
                style = MaterialTheme.typography.titleSmall,
                color = Color.White,
                fontWeight = FontWeight.SemiBold,
            )
            Spacer(modifier = Modifier.height(8.dp))
            OutlinedButton(
                onClick = {
                    val pass = Passphrase.generate()
                    generated = pass
                    passphrase = pass
                    showPassphrase = true
                    status = "Random passphrase ready — create your account next."
                },
                enabled = !busy,
                modifier = Modifier.fillMaxWidth(),
                shape = RoundedCornerShape(6.dp),
            ) { Text("Generate passphrase") }

            if (generated != null) {
                Spacer(modifier = Modifier.height(10.dp))
                Text(
                    generated!!,
                    style = MaterialTheme.typography.titleSmall,
                    fontFamily = FontFamily.Monospace,
                    color = MaterialTheme.colorScheme.primary,
                    textAlign = TextAlign.Center,
                )
                Text(
                    "Write this down — it’s your host login secret.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    textAlign = TextAlign.Center,
                )
            }

            Spacer(modifier = Modifier.height(10.dp))
            Button(
                onClick = {
                    run("Creating account...") {
                        val user = username.trim()
                        val pass = passphrase.trim().ifBlank {
                            Passphrase.generate().also {
                                generated = it
                                passphrase = it
                                showPassphrase = true
                            }
                        }
                        require(user.length in 3..32) { "username must be 3–32 chars" }
                        require(pass.length >= 10) { "passphrase too short" }
                        val res = api.signup(user, pass)
                        session.token = res.token
                        session.username = res.username
                        persistIfNeeded(user, pass)
                        onSignedIn()
                        "Account created. You’re in."
                    }
                },
                enabled = !busy && username.length >= 3,
                modifier = Modifier
                    .fillMaxWidth()
                    .height(48.dp),
                shape = RoundedCornerShape(6.dp),
                colors = ButtonDefaults.buttonColors(
                    containerColor = MaterialTheme.colorScheme.primary,
                    contentColor = Color.White,
                ),
            ) {
                Text("Create account", fontWeight = FontWeight.Bold)
            }

            Spacer(modifier = Modifier.height(20.dp))
            Text(
                status,
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                textAlign = TextAlign.Center,
            )
        }
    }
}
